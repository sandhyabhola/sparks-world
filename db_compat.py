"""Database layer for Sparks World: Neon (PostgreSQL) with a SQLite-style API.

main.py keeps using db.execute("... ? ..."), row["name"] and row[0], cursor.lastrowid and db.commit().
This module turns those calls into PostgreSQL and keeps a small connection pool so pages stay fast
and connections that Neon closed while idle are replaced automatically.
"""
from __future__ import annotations

import os
import re
import time
from typing import Any

import psycopg
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

IntegrityError = psycopg.IntegrityError
OperationalError = psycopg.OperationalError

# Tables whose "id" column is generated by the database (used to emulate cursor.lastrowid).
_ID_TABLES = {"users", "questions", "answers", "art", "comments", "qbank", "task_log", "acomments"}


class CompatRow(dict):
    """A row that supports row["name"] and row[0], like sqlite3.Row."""

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            try:
                key = list(self.keys())[key]
            except IndexError:
                raise IndexError(key) from None
        return super().__getitem__(key)


class CompatCursor:
    """Holds the rows already fetched, so the connection can go back to the pool right away."""

    def __init__(self, rows: list, rowcount: int, lastrowid: int | None):
        self._rows = rows
        self.rowcount = rowcount
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._rows.pop(0) if self._rows else None

    def fetchall(self):
        out, self._rows = self._rows, []
        return out


def _translate(statement: str) -> tuple[str, bool]:
    """SQLite-style SQL -> PostgreSQL. Returns (sql, wants_returning_id)."""
    original = statement.strip()
    sql = original.replace("?", "%s")  # the app never uses a literal ? or % inside its SQL

    # INSERT OR REPLACE is only used for one-time-code records.
    m = re.match(r"(?is)^INSERT\s+OR\s+REPLACE\s+INTO\s+pending\s*\((.*?)\)\s*VALUES\s*\((.*?)\)(.*)$", sql)
    if m:
        cols, vals, tail = m.groups()
        sql = (f"INSERT INTO pending ({cols}) VALUES ({vals}) ON CONFLICT (kind, key) DO UPDATE SET "
               "data=EXCLUDED.data, otp=EXCLUDED.otp, exp=EXCLUDED.exp, tries=EXCLUDED.tries, sent=EXCLUDED.sent" + tail)

    # Table definitions: identity ids, and real timestamps (REAL in PostgreSQL is only 4 bytes: too coarse for time.time()).
    if re.match(r"(?is)^CREATE\s+TABLE\b", sql):
        sql = re.sub(r"(?i)\bINTEGER\s+PRIMARY\s+KEY\b", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
        sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)

    # Adding a column that already exists must not fail.
    sql = re.sub(r"(?i)(ALTER\s+TABLE\s+\S+\s+ADD\s+COLUMN)(?!\s+IF\s+NOT\s+EXISTS)", r"\1 IF NOT EXISTS", sql)

    # Old code reads cursor.lastrowid after INSERT: ask PostgreSQL to return the new id.
    returning = False
    im = re.match(r"(?is)^INSERT\s+INTO\s+([a-z_][a-z0-9_]*)\s*\((.*?)\)\s*VALUES\b", original)
    if im and im.group(1).lower() in _ID_TABLES and not re.search(r"(?i)\bRETURNING\b", sql):
        cols = [c.strip().strip('"`').lower() for c in im.group(2).split(",")]
        if "id" not in cols:
            sql += " RETURNING id"
            returning = True
    return sql, returning


class PostgresCompat:
    def __init__(self, dsn: str | None):
        if not dsn:
            raise RuntimeError("DATABASE_URL is missing. Put it in your local .env file or in your host's environment settings.")
        self._pool = ConnectionPool(
            dsn,
            min_size=1,
            max_size=int(os.getenv("DB_POOL_MAX", "6")),
            kwargs={"autocommit": True, "row_factory": dict_row, "prepare_threshold": None, "connect_timeout": 15},
            max_idle=240,        # drop connections that sat idle longer than 4 minutes (Neon suspends after 5)
            max_lifetime=1800,
            open=False,
        )
        self._pool.open(wait=True, timeout=45)

    def execute(self, statement: str, params=()):
        sql, returning = _translate(statement)
        last: Exception | None = None
        for attempt in range(3):  # a connection that Neon closed while idle fails once, then a fresh one is used
            try:
                with self._pool.connection() as conn:
                    cur = conn.execute(sql, params if params else None)
                    fetched = cur.fetchall() if cur.description else []
                    rowcount = cur.rowcount
                break
            except psycopg.OperationalError as e:
                last = e
                time.sleep(0.25 * attempt)
        else:
            raise last  # type: ignore[misc]
        rows = [CompatRow(r) for r in fetched]
        lastrowid = rows[0].get("id") if (returning and rows) else None
        return CompatCursor(rows, rowcount, lastrowid)

    def executescript(self, script: str):
        for statement in script.split(";"):
            statement = statement.strip()
            if statement:
                self.execute(statement)

    def finish_setup(self):
        """Run once after all tables are created: fix old column types and id defaults."""
        try:
            # Timestamps created earlier as REAL (4 bytes) lose precision: widen them.
            for r in self.execute("SELECT table_name t, column_name c FROM information_schema.columns "
                                  "WHERE table_schema=current_schema() AND data_type='real'").fetchall():
                self.execute(f'ALTER TABLE "{r["t"]}" ALTER COLUMN "{r["c"]}" TYPE DOUBLE PRECISION')
            # Tables made earlier without automatic ids get them, and the counter starts after the highest id.
            for table in sorted(_ID_TABLES):
                row = self.execute("SELECT column_default d, is_identity i FROM information_schema.columns "
                                   "WHERE table_schema=current_schema() AND table_name=? AND column_name='id'", (table,)).fetchone()
                if row and row["i"] != "YES" and row["d"] is None:
                    self.execute(f'ALTER TABLE "{table}" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY')
                    self.execute(f"SELECT setval(pg_get_serial_sequence('{table}','id'), "
                                 f"(SELECT COALESCE(MAX(id),0)+1 FROM {table}), false)")
        except Exception as e:  # never stop the app from starting because of a clean-up step
            print("database clean-up skipped:", type(e).__name__, str(e)[:200])

    def commit(self):  # autocommit is on: every statement is saved immediately
        pass

    def rollback(self):
        pass

    def close(self):
        self._pool.close()


db = PostgresCompat(os.getenv("DATABASE_URL"))
